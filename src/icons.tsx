export type IconName = keyof typeof ICONS

export function Icon({ name, size = 16, color }: { name: IconName; size?: number; color: string }) {
  return <svg source={ICONS[name]} style={{ width: size, height: size, flexShrink: 0, color }} />
}

export function IconButton({
  icon,
  onClick,
  size = 16,
  pad = 28,
  color,
  dimmed,
  plain,
  active,
  testId,
  tooltip,
}: {
  /** Shown while the pointer rests on the button: what it does, since there's no text. */
  tooltip?: string
  icon: IconName
  onClick?: () => void
  size?: number
  pad?: number
  color?: string
  dimmed?: boolean
  /** No hover box: the icon itself is the hit target, so it can sit flush on an alignment edge. */
  plain?: boolean
  /** Toggled-on state, e.g. an open menu's trigger. */
  active?: boolean
  testId?: string
}) {
  const { C } = useSettings()
  const button = (
    <div
      testId={testId}
      onClick={onClick}
      style={{
        width: pad,
        height: pad,
        flexShrink: 0,
        borderRadius: 8,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        cursor: 'pointer',
        opacity: dimmed ? 0.4 : 1,
        backgroundColor: active ? C.overlayStrong : undefined,
        hover: dimmed || plain ? { opacity: 0.7 } : { backgroundColor: C.overlay },
        active: dimmed || plain ? undefined : { backgroundColor: C.overlayStrong },
      }}
    >
      <Icon name={icon} size={size} color={color ?? (active ? C.text : C.muted)} />
    </div>
  )
  return tooltip ? <Tooltip label={tooltip}>{button}</Tooltip> : button
}
