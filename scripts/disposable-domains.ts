/**
 * Refreshes the throwaway-mailbox list the contact form checks against.
 *
 *   bun run domains
 *
 * The source is disposable-email-domains, which is a plain newline-separated file of domains:
 * https://github.com/disposable-email-domains/disposable-email-domains
 *
 * It is vendored rather than fetched at runtime — a Worker handling a contact form should not
 * depend on GitHub being up, and a list that changes under us would make failures unrepeatable.
 * Re-run this when it's worth picking up new domains; the diff is the review.
 */
import { writeFileSync } from 'node:fs'
import { WEBSITE } from './website-dir'

const SOURCE = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf'
const OUT = `${WEBSITE}/src/server/disposable-domains.ts`

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`${SOURCE} returned ${response.status}`)

const domains = [
  ...new Set(
    (await response.text())
      .split('\n')
      .map((line) => line.trim().toLowerCase())
      .filter((line) => line && !line.startsWith('#') && line.includes('.')),
  ),
].sort()

// A sanity floor: a truncated download must not quietly turn the filter off.
if (domains.length < 5000) throw new Error(`only ${domains.length} domains — the download looks truncated`)

const file = `// Generated by \`bun run domains\` on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.
// Source: ${SOURCE}
// ${domains.length} domains, under CC0-1.0.

/** One domain per line, kept as text: it is a fraction of the size of ${domains.length} quoted strings. */
const LIST = \`${domains.join('\n')}\`

export const DISPOSABLE_DOMAINS: ReadonlySet<string> = new Set(LIST.split('\\n'))
`

writeFileSync(OUT, file)
console.log(`wrote ${OUT} (${domains.length} domains, ${(file.length / 1024).toFixed(0)} KB)`)
